import { AgentAdapter, CapabilityManifest, RoleResolution, SoundcheckConfig } from '../../types/soundcheck';

export function generateCapabilityManifest(
  adapters: AgentAdapter[],
  resolvedRoles: Record<string, RoleResolution>,
  hostInfo: { platform: string; nodeVersion: string; gitWorktree: boolean }
): CapabilityManifest {
  const agentsSummary: CapabilityManifest['agents'] = {};

  let functionalCount = 0;
  let cooldownCount = 0;

  for (const a of adapters) {
    const isCooldown = !!(a.cooldownUntil && a.cooldownUntil > Date.now());
    const isFunctional = a.installed && a.probes.L1.status === 'passed' && !isCooldown;

    if (isFunctional) functionalCount++;
    if (isCooldown) cooldownCount++;

    agentsSummary[a.id] = {
      installed: a.installed,
      version: a.versionDetected,
      authValid: a.probes.L1.status === 'passed',
      functional: isFunctional,
      cooldownActive: isCooldown,
      errorClass: a.probes.L2.errorClass || 'ok',
      models: a.models.map((m) => m.id),
      permissions: a.permissionModes
    };
  }

  return {
    schemaVersion: '2026.1',
    generatedAt: new Date().toISOString(),
    host: hostInfo,
    summary: {
      totalAgents: adapters.length,
      functionalAgents: functionalCount,
      cooldownsActive: cooldownCount,
      quirksProtected: adapters.reduce((acc, a) => acc + a.quirks.length, 0)
    },
    agents: agentsSummary,
    resolvedRoles: {
      primary: {
        agent: resolvedRoles.primary?.selectedAgentId || 'none',
        model: resolvedRoles.primary?.selectedModel || 'none',
        vendor: resolvedRoles.primary?.vendor || 'none',
        reason: resolvedRoles.primary?.reasoning || 'none'
      },
      subagent: {
        agent: resolvedRoles.subagent?.selectedAgentId || 'none',
        model: resolvedRoles.subagent?.selectedModel || 'none',
        vendor: resolvedRoles.subagent?.vendor || 'none',
        reason: resolvedRoles.subagent?.reasoning || 'none'
      },
      auxiliary: {
        agent: resolvedRoles.auxiliary?.selectedAgentId || 'none',
        model: resolvedRoles.auxiliary?.selectedModel || 'none',
        vendor: resolvedRoles.auxiliary?.vendor || 'none',
        reason: resolvedRoles.auxiliary?.reasoning || 'none'
      },
      reviewer: {
        agent: resolvedRoles.reviewer?.selectedAgentId || 'none',
        model: resolvedRoles.reviewer?.selectedModel || 'none',
        vendor: resolvedRoles.reviewer?.vendor || 'none',
        reason: resolvedRoles.reviewer?.reasoning || 'none'
      }
    }
  };
}

export function generateCrewplaneHook(manifest: CapabilityManifest): string {
  return `#!/usr/bin/env python3
"""
Crewplane Provider Selection Hook generated by Soundcheck (October 2026)
Consumes capability manifest to dynamically resolve roles without burning quota.
"""
import json
import sys

MANIFEST = json.loads('''${JSON.stringify(manifest, null, 2)}''')

def get_agent_for_role(role_name: str) -> dict:
    resolved = MANIFEST.get("resolvedRoles", {}).get(role_name)
    if not resolved:
        raise RuntimeError(f"Soundcheck: Role {role_name} has no resolved healthy agent.")
    return resolved

if __name__ == "__main__":
    requested_role = sys.argv[1] if len(sys.argv) > 1 else "primary"
    result = get_agent_for_role(requested_role)
    print(f"{result['agent']}:{result['model']}")
`;
}

